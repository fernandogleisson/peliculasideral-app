#!/usr/bin/env node
/**
 * Converts the JSON output of `design.md export DESIGN.md --format tailwind`
 * into a Tailwind v4 `@theme` CSS block written to src/app/design-tokens.css.
 *
 * Why: the design.md CLI only emits a Tailwind v3 config object as JSON; the
 * project uses Tailwind v4 which expects CSS-first `@theme` blocks. This
 * adapter bridges the gap so DESIGN.md remains the single source of truth.
 */

import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(process.cwd());
const out = resolve(root, 'src/app/design-tokens.css');

const proc = spawnSync('pnpm', ['exec', 'design.md', 'export', 'DESIGN.md', '--format', 'tailwind'], {
  encoding: 'utf8',
  cwd: root,
});

if (proc.status !== 0) {
  process.stderr.write(proc.stderr || 'design.md export failed\n');
  process.exit(proc.status ?? 1);
}

// pnpm prefixes stdout with the lifecycle banner; strip everything before the first `{`.
const raw = proc.stdout;
const start = raw.indexOf('{');
if (start === -1) {
  process.stderr.write('Could not find JSON object in design.md export output\n');
  process.exit(1);
}
const payload = JSON.parse(raw.slice(start));
const ext = payload?.theme?.extend ?? {};

const lines = [
  '/* AUTO-GENERATED by `pnpm design:export` from DESIGN.md. DO NOT EDIT. */',
  '',
  '@theme inline {',
];

const colors = ext.colors ?? {};
for (const [name, value] of Object.entries(colors)) {
  lines.push(`  --color-${name}: ${value};`);
}

const fontFamily = ext.fontFamily ?? {};
for (const [name, value] of Object.entries(fontFamily)) {
  const stack = Array.isArray(value) ? value.join(', ') : value;
  lines.push(`  --font-${name}: ${stack};`);
}

const fontSize = ext.fontSize ?? {};
for (const [name, value] of Object.entries(fontSize)) {
  const size = Array.isArray(value) ? value[0] : value;
  const meta = Array.isArray(value) ? value[1] ?? {} : {};
  lines.push(`  --text-${name}: ${size};`);
  if (meta.lineHeight) lines.push(`  --text-${name}--line-height: ${meta.lineHeight};`);
  if (meta.letterSpacing) lines.push(`  --text-${name}--letter-spacing: ${meta.letterSpacing};`);
  if (meta.fontWeight) lines.push(`  --text-${name}--font-weight: ${meta.fontWeight};`);
}

const borderRadius = ext.borderRadius ?? {};
for (const [name, value] of Object.entries(borderRadius)) {
  const key = name === 'DEFAULT' ? '' : `-${name}`;
  lines.push(`  --radius${key}: ${value};`);
}

const spacing = ext.spacing ?? {};
for (const [name, value] of Object.entries(spacing)) {
  const safe = name.replace(/\./g, '_');
  lines.push(`  --spacing-${safe}: ${value};`);
}

lines.push('}');
lines.push('');

writeFileSync(out, lines.join('\n'), 'utf8');
process.stderr.write(`Wrote ${out}\n`);
